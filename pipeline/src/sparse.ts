/** FNV-1a hash → uint32. Deterministic, no shared state needed. */
export function hashToken(token: string): number {
  let hash = 0x811c9dc5;
  for (let i = 0; i < token.length; i++) {
    hash ^= token.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return hash >>> 0;
}

/** Tokenize: lowercase, split on non-alphanumeric, remove stopwords, min 2 chars */
export function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .split(/[^a-zäöüß0-9]+/)
    .filter((t) => t.length >= 2 && !STOPWORDS.has(t));
}

/** BM25-TF saturation sparse vector: weight = tf / (tf + 1.2) */
export function computeSparseVector(text: string): { indices: number[]; values: number[] } {
  const tokens = tokenize(text);
  if (tokens.length === 0) return { indices: [], values: [] };

  // Count term frequencies
  const tf = new Map<string, number>();
  for (const token of tokens) {
    tf.set(token, (tf.get(token) ?? 0) + 1);
  }

  // Convert to sparse vector with BM25-TF saturation
  const indices: number[] = [];
  const values: number[] = [];

  for (const [token, count] of tf) {
    indices.push(hashToken(token));
    values.push(count / (count + 1.2));
  }

  return { indices, values };
}
